import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src', 'data');
const outFile = join(root, 'supabase', 'seed.sql');

const read = (file) => JSON.parse(readFileSync(join(dataDir, file), 'utf8'));
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

const brands = read('brands.json');
const models = read('carModels.json');
const variants = read('carVariants.json');
const groups = read('featureGroups.json');
const features = read('features.json');
const links = read('carVariantFeatures.json');

const insert = (table, columns, rows) => {
  if (rows.length === 0) return '';
  const values = rows
    .map((row) => `  (${row.map((value) => (typeof value === 'number' ? value : typeof value === 'boolean' ? value : quote(value))).join(', ')})`)
    .join(',\n');
  return `insert into ${table} (${columns.join(', ')}) overriding system value values\n${values};\n`;
};

const sections = [
  `-- Generated by scripts/generate-seed.mjs. Do not edit by hand.\n-- Paste into the Supabase SQL Editor after the schema migration.\n\nbegin;\n`,
  insert(
    'brands',
    ['id', 'name', 'origin', 'logo_text'],
    brands.map((brand) => [brand.id, brand.name, brand.origin, brand.logoText]),
  ),
  insert(
    'car_models',
    ['id', 'brand_id', 'name', 'body_type', 'safety_rating', 'colors'],
    models.map((model) => [model.id, model.brandId, model.name, model.bodyType, model.safetyRating, model.colors]),
  ),
  insert(
    'car_variants',
    ['id', 'model_id', 'trim_name', 'price_lakh', 'fuel_type', 'transmission', 'seats', 'engine_cc', 'power_bhp', 'mileage_kmpl'],
    variants.map((variant) => [
      variant.id,
      variant.modelId,
      variant.trimName,
      variant.priceLakh,
      variant.fuelType,
      variant.transmission,
      variant.seats,
      variant.engineCc,
      variant.powerBhp,
      variant.mileageKmpl,
    ]),
  ),
  insert(
    'feature_groups',
    ['id', 'label', 'sort_order'],
    groups.map((group) => [group.id, group.label, group.sortOrder]),
  ),
  insert(
    'features',
    ['id', 'group_id', 'label', 'sort_order'],
    features.map((feature) => [feature.id, feature.groupId, feature.label, feature.sortOrder]),
  ),
  insert(
    'car_variant_features',
    ['id', 'variant_id', 'feature_id', 'is_standard'],
    links.map((link) => [link.id, link.variantId, link.featureId, link.isStandard]),
  ),
  ['brands', 'car_models', 'car_variants', 'feature_groups', 'features', 'car_variant_features']
    .map((table) => `select setval(pg_get_serial_sequence('${table}', 'id'), (select max(id) from ${table}));`)
    .join('\n'),
  '\ncommit;\n',
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sections.join('\n'), 'utf8');
console.log(`Wrote ${outFile}`);
